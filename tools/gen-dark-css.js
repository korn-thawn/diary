// Generates client/src/dark.css: the noir ("บันทึกหลังเที่ยงคืน") overrides of Tailwind's color variables.
// Run after upgrading Tailwind or changing a value here:  node tools/gen-dark-css.js
// The app is dark-only, so the block applies on :root (and .dark, which /theme.js always sets, so
// the few dark: variants keep working). Instead of restyling every component, the grey scale is
// replaced by green-black greys and each hue's light tints / dark shades are remapped for a dark surface.
const fs = require("node:fs");
const path = require("node:path");

const theme = fs.readFileSync(require.resolve("tailwindcss/theme.css"), "utf8");
const v = (name) => {
  const m = new RegExp(`--color-${name}:\\s*([^;]+);`).exec(theme);
  if (!m) throw new Error(`missing --color-${name}`);
  return m[1].trim();
};

const HUES = ["rose", "red", "orange", "amber", "lime", "emerald", "teal", "sky", "indigo", "fuchsia"];
// green-black greys built around the handoff's line / text tokens (500 = --text-dim, 600 = --text-muted)
const STONE = {
  50: "#131c1b", 100: "#1a2422", 200: "#22302d", 300: "#3a4a46", 400: "#6e7e79",
  500: "#9ba8a3", 600: "#b9c4bf", 700: "#d4d9d2", 800: "#e6e3d8", 900: "#f2e8d5", 950: "#fbf5e8",
};

const lines = [
  "/* GENERATED by tools/gen-dark-css.js — do not edit by hand */",
  ":root, .dark {",
  "  color-scheme: dark;",
  ...Object.entries(STONE).map(([k, c]) => `  --color-stone-${k}: ${c};`),
];
for (const h of HUES) {
  const mid = v(`${h}-500`);
  lines.push(
    `  --color-${h}-50: color-mix(in oklab, ${mid} 14%, var(--color-surface));`,
    `  --color-${h}-100: color-mix(in oklab, ${mid} 20%, var(--color-surface));`,
    `  --color-${h}-200: color-mix(in oklab, ${mid} 32%, var(--color-surface));`,
    `  --color-${h}-700: ${v(`${h}-300`)};`,
    `  --color-${h}-800: ${v(`${h}-200`)};`,
    `  --color-${h}-900: ${v(`${h}-100`)};`
  );
}
// error text (red-600) needs more contrast on dark
lines.push(`  --color-red-600: ${v("red-400")};`);
// mood scale 1-5 on the noir surface (validated with the dataviz palette checker, always shown with labels)
lines.push("  --mood-1: #f43f5e;", "  --mood-2: #fecdd3;", "  --mood-3: #a8a29e;", "  --mood-4: #a7f3d0;", "  --mood-5: #10b981;");
lines.push("}", "");

const out = path.join(__dirname, "..", "client", "src", "dark.css");
fs.writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out} (${lines.length} lines)`);

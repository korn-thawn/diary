// Generates client/src/dark.css: dark-mode overrides of Tailwind's color variables.
// Run after upgrading Tailwind:  node tools/gen-dark-css.js
// Approach: instead of adding dark: variants to every component, the .dark class remaps
// the stone scale (mirrored), the light tints (50-200) and dark shades (700-900) of each hue.
const fs = require("node:fs");
const path = require("node:path");

const theme = fs.readFileSync(require.resolve("tailwindcss/theme.css"), "utf8");
const v = (name) => {
  const m = new RegExp(`--color-${name}:\\s*([^;]+);`).exec(theme);
  if (!m) throw new Error(`missing --color-${name}`);
  return m[1].trim();
};

const SURFACE = "#25362b";
const HUES = ["rose", "red", "orange", "amber", "lime", "emerald", "teal", "sky", "indigo", "fuchsia"];
const STONE = { // green-tinted greys to match the night desk
  50: "#22322a", 100: "#2a3b31", 200: "#38493e", 300: "#4d5f53", 400: "#879489",
  500: "#a7b2a8", 600: "#c3ccc3", 700: "#d8ddd4", 800: "#e8ebe2", 900: "#f4f5ef", 950: "#fafbf6",
};

const lines = [
  "/* GENERATED by tools/gen-dark-css.js — do not edit by hand */",
  ".dark {",
  "  color-scheme: dark;",
  // "desk at night": deep green desk, dark green-grey windows, cream ink
  "  --color-desk: #10241a;",
  "  --color-desk-dot: #183326;",
  "  --color-paper: #1c2a21;",
  `  --color-surface: ${SURFACE};`,
  "  --color-ink: #efe6cf;",
  "  --color-shadow: #050d08;",
  "  --color-title: #2f7f50;",
  "  --color-on-title: #fbf5e6;",
  "  --color-accent: #6cc28f;",
  "  --color-highlight: #d9b94a;",
  "  --color-on-highlight: #1c2a20;",
  ...Object.entries(STONE).map(([k, c]) => `  --color-stone-${k}: ${c};`),
];
for (const h of HUES) {
  const mid = v(`${h}-500`);
  lines.push(
    `  --color-${h}-50: color-mix(in oklab, ${mid} 14%, var(--color-surface));`,
    `  --color-${h}-100: color-mix(in oklab, ${mid} 20%, var(--color-surface));`,
    `  --color-${h}-200: color-mix(in oklab, ${mid} 32%, var(--color-surface));`,
    `  --color-${h}-700: ${v(`${h}-300`)};`,
    `  --color-${h}-800: ${v(`${h}-200`)};`,
    `  --color-${h}-900: ${v(`${h}-100`)};`
  );
}
// error text (red-600) needs more contrast on dark
lines.push(`  --color-red-600: ${v("red-400")};`);
// mood scale for dark surfaces (validated with the dataviz palette checker, always shown with labels)
lines.push("  --mood-1: #f43f5e;", "  --mood-2: #fecdd3;", "  --mood-3: #a8a29e;", "  --mood-4: #a7f3d0;", "  --mood-5: #10b981;");
lines.push("}", "");

const out = path.join(__dirname, "..", "client", "src", "dark.css");
fs.writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out} (${lines.length} lines)`);

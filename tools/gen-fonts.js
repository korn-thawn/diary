// Generates client/src/fonts.generated.js: lazy loaders for the Thai fonts a user can pick.
// Each weight is its own dynamic import (Rspack makes a small CSS chunk per file), so only the
// fonts and weights actually used are downloaded. Run after adding a font:  node tools/gen-fonts.js
// Keep the ids in sync with FONTS in server/appearance.js.
const fs = require("node:fs");
const path = require("node:path");

// id (= @fontsource package) → [family, fallback kind, label]
const FONTS = {
  "ibm-plex-sans-thai": ["IBM Plex Sans Thai", "sans-serif", "IBM Plex Sans Thai"],
  "chakra-petch": ["Chakra Petch", "sans-serif", "Chakra Petch"],
  sarabun: ["Sarabun", "sans-serif", "Sarabun"],
  "noto-sans-thai": ["Noto Sans Thai", "sans-serif", "Noto Sans Thai"],
  anuphan: ["Anuphan", "sans-serif", "Anuphan"],
  prompt: ["Prompt", "sans-serif", "Prompt"],
  kanit: ["Kanit", "sans-serif", "Kanit"],
  mitr: ["Mitr", "sans-serif", "Mitr"],
  "bai-jamjuree": ["Bai Jamjuree", "sans-serif", "Bai Jamjuree"],
  k2d: ["K2D", "sans-serif", "K2D"],
  "noto-serif-thai": ["Noto Serif Thai", "serif", "Noto Serif Thai"],
  mali: ["Mali", "cursive", "Mali"],
  itim: ["Itim", "cursive", "Itim"],
};
const WANT = [400, 500, 600, 700];

const root = path.join(__dirname, "..");
const out = [
  "// GENERATED by tools/gen-fonts.js — do not edit by hand",
  "/* eslint-disable */",
  "export const FONTS = {",
];
for (const [id, [family, kind, label]] of Object.entries(FONTS)) {
  const dir = path.join(root, "node_modules", "@fontsource", id);
  const have = WANT.filter((w) => fs.existsSync(path.join(dir, `thai-${w}.css`)));
  if (!have.length) throw new Error(`${id}: no thai weights`);
  out.push(`  ${JSON.stringify(id)}: {`);
  out.push(`    family: ${JSON.stringify(family)}, kind: ${JSON.stringify(kind)}, label: ${JSON.stringify(label)},`);
  out.push(`    weights: {`);
  for (const w of have) {
    out.push(`      ${w}: () => Promise.all([import("@fontsource/${id}/thai-${w}.css"), import("@fontsource/${id}/latin-${w}.css")]),`);
  }
  out.push("    },", "  },");
}
out.push("};", "");
const file = path.join(root, "client", "src", "fonts.generated.js");
fs.writeFileSync(file, out.join("\n"));
console.log(`wrote ${file}`);
